import React, { useState, useEffect } from 'react';
import { RefreshCw, Activity } from 'lucide-react';
import { api } from '../services/api';

export default function TrafficPage() {
  const [records, setRecords] = useState([]);
  const [stats, setStats] = useState(null);
  const [loading, setLoading] = useState(true);
  const [anomalyOnly, setAnomalyOnly] = useState(false);
  const [pulsing, setPulsing] = useState(false);

  const load = async () => {
    setLoading(true);
    try {
      const [t, s] = await Promise.all([api.getTraffic(100, anomalyOnly), api.getTrafficStats()]);
      const items = Array.isArray(t) ? t : (t.records || t.items || []);
      setRecords(items);
      setStats(s);
    } catch (e) { console.error(e); }
    finally { setLoading(false); }
  };

  useEffect(() => { load(); const iv = setInterval(load, 5000); return () => clearInterval(iv); }, [anomalyOnly]);

  const pulse = async () => {
    setPulsing(true);
    try { await api.pulseTraffic(8); await load(); }
    catch (e) { console.error(e); }
    finally { setPulsing(false); }
  };

  const formatBytes = (b) => b >= 1_000_000 ? `${(b/1_000_000).toFixed(1)} MB` : b >= 1000 ? `${(b/1000).toFixed(1)} KB` : `${b} B`;

  return (
    <div style={{ padding: '24px 0', maxWidth: 1240, margin: '0 auto' }}>
      <div style={{ display: 'flex', alignItems: 'flex-start', justifyContent: 'space-between', marginBottom: 20, gap: 12, flexWrap: 'wrap' }}>
        <div>
          <h1 style={{ fontSize: '1.5rem', fontWeight: 800, color: '#0f172a' }}>Network Traffic</h1>
          <p style={{ fontSize: '0.8125rem', color: '#64748b', marginTop: 2 }}>
            Synthetic traffic flows generated by the simulation engine · <span className="tag-simulated">SIMULATED</span>
          </p>
        </div>
        <div style={{ display: 'flex', gap: 8 }}>
          <label style={{ display: 'flex', alignItems: 'center', gap: 8, fontSize: '0.8125rem', color: '#334155', cursor: 'pointer' }}>
            <input type="checkbox" checked={anomalyOnly} onChange={e => setAnomalyOnly(e.target.checked)} style={{ accentColor: '#dc2626' }} />
            Anomalies Only
          </label>
          <button onClick={pulse} disabled={pulsing} className="btn btn-primary btn-sm">
            <Activity size={13} /> {pulsing ? 'Generating…' : 'Generate Pulse'}
          </button>
          <button onClick={load} className="btn btn-ghost btn-sm"><RefreshCw size={13} /></button>
        </div>
      </div>

      {/* Stats */}
      {stats && (
        <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(140px, 1fr))', gap: 12, marginBottom: 20 }}>
          {[
            ['Total Flows', stats.total_flows || records.length, '#2563eb'],
            ['Total Bytes', formatBytes(stats.total_bytes || 0), '#7c3aed'],
            ['Anomalies', stats.anomaly_count || 0, '#dc2626'],
            ['Protocols', stats.protocol_count || '—', '#059669'],
          ].map(([l, v, c]) => (
            <div key={l} className="kpi-card" style={{ borderTop: `3px solid ${c}` }}>
              <span className="kpi-label">{l}</span>
              <span className="kpi-value" style={{ color: c }}>{v}</span>
            </div>
          ))}
        </div>
      )}

      {/* Table */}
      <div className="ng-table-wrap">
        <table className="ng-table">
          <thead>
            <tr>
              <th>Timestamp</th>
              <th>Source Type</th>
              <th>Source IP</th>
              <th>Destination IP</th>
              <th>Protocol</th>
              <th>Src Port</th>
              <th>Dst Port</th>
              <th>Packets</th>
              <th>Bytes</th>
              <th>Anomaly</th>
            </tr>
          </thead>
          <tbody>
            {loading ? (
              <tr><td colSpan={10} style={{ textAlign: 'center', padding: 32, color: '#94a3b8' }}>Loading…</td></tr>
            ) : records.length === 0 ? (
              <tr><td colSpan={10} style={{ textAlign: 'center', padding: 32, color: '#94a3b8' }}>No traffic records. Click "Generate Pulse" to create traffic.</td></tr>
            ) : records.map((r, i) => (
              <tr key={i} style={r.is_anomalous ? { background: '#fff5f5' } : {}}>
                <td style={{ fontSize: '0.75rem', color: '#64748b', fontFamily: 'monospace' }}>{r.timestamp ? new Date(r.timestamp).toLocaleTimeString() : '—'}</td>
                <td>
                  {r.data_source === 'OBSERVED' ? (
                    <span className="tag-observed">OBSERVED</span>
                  ) : (
                    <span className="tag-simulated">SIMULATED</span>
                  )}
                </td>
                <td style={{ fontFamily: 'monospace', fontSize: '0.8125rem' }}>{r.source_ip}</td>
                <td style={{ fontFamily: 'monospace', fontSize: '0.8125rem' }}>{r.destination_ip}</td>
                <td><span className="badge badge-info">{r.protocol}</span></td>
                <td style={{ fontFamily: 'monospace' }}>{r.source_port}</td>
                <td style={{ fontFamily: 'monospace' }}>{r.destination_port}</td>
                <td>{r.packet_count}</td>
                <td>{formatBytes(r.bytes || 0)}</td>
                <td>
                  {r.is_anomalous
                    ? <span className="badge badge-high">⚠️ ANOMALOUS</span>
                    : <span className="badge badge-normal">✓ Normal</span>
                  }
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}
